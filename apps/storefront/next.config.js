/** @type {import('next').NextConfig} */
const createNextIntlPlugin = require("next-intl/plugin");

// Points next-intl at the request config that chooses which message catalogue a
// render uses. Without this the provider throws "Couldn't find next-intl config
// file" at build time.
const withNextIntl = createNextIntlPlugin("./i18n/request.ts");
const backendUrl = new URL(
  process.env.MEDUSA_BACKEND_URL ||
    process.env.NEXT_PUBLIC_MEDUSA_BACKEND_URL ||
    "http://localhost:9000"
);

const nextConfig = {
  // The dev-mode indicator is a floating badge that sits over the bottom-left of
  // every page — which is exactly where the cookie banner is. It never ships to
  // production, but it does hide content in previews and screenshots, so it is
  // switched off.
  devIndicators: false,
  reactStrictMode: true,
  poweredByHeader: false,
  eslint: {
    ignoreDuringBuilds: true,
  },
  compress: true,
  transpilePackages: ["@snehavrinda-kala/ui", "@snehavrinda-kala/types"],
  // Standalone output is only needed for the container image. Local builds
  // keep the regular Next.js server so `next start` works without warnings.
  output: process.env.NEXT_STANDALONE === "true" ? "standalone" : undefined,
  images: {
    remotePatterns: [
      { protocol: "https", hostname: backendUrl.hostname },
      { protocol: "http", hostname: backendUrl.hostname },
      // S3 / CloudFront media storage (build plan Section 12.6)
      {
        protocol: "https",
        hostname: process.env.NEXT_PUBLIC_MEDIA_DOMAIN || "media.snehavrindakala.example",
      },
    ],
  },
  async redirects() {
    // Seed products once shipped with opaque handles (`/products/003`) taken
    // from their database ids. Those URLs may already be in a browser history,
    // a share, or a search index, so redirect each to its readable slug rather
    // than 404. Order matters: a specific id must be listed before a catch-all.
    //
    // Five of these six destinations used to be invented slugs
    // (`...-home-1`, `...-traditional-2`, `...-textile-3`) generated by an
    // older slug scheme that prepended the category name and appended a
    // position. No product carries those handles, so the redirect chain ended
    // on a 404 — a permanent redirect into a dead page, which is worse than no
    // redirect at all, because a crawler replaces the old URL with the new
    // broken one. Each destination below is a handle that currently resolves.
    //
    // `next.config.js` cannot read the database, so this table goes stale when
    // a product is renamed or deleted. `scripts/check-redirects.mjs` walks it
    // against a running storefront and fails loudly when a destination stops
    // resolving; run it after any catalogue change.
    return [
      { source: "/products/001", destination: "/products/hand-painted-terracotta-vase", permanent: true },
      { source: "/products/002", destination: "/products/madhubani-folk-painting", permanent: true },
      { source: "/products/003", destination: "/products/embroidered-cotton-throw", permanent: true },
      { source: "/products/004", destination: "/products/custom-portrait-commission", permanent: true },
      { source: "/products/005", destination: "/products/pattachitra-scroll-panel", permanent: true },
      { source: "/products/006", destination: "/products/silver-filigree-earrings", permanent: true },
    ];
  },
  async headers() {
    const headers = [
      { key: "X-Content-Type-Options", value: "nosniff" },
      { key: "X-Frame-Options", value: "DENY" },
      { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
      {
        key: "Permissions-Policy",
        value: "camera=(), microphone=(), geolocation=()",
      },
      {
        key: "Content-Security-Policy",
        value:
          "default-src 'self'; " +
          // Razorpay's checkout is not one host. `checkout.razorpay.com` serves the
          // document and assets, `api.razorpay.com` is framed for the payment
          // methods, and `lumberjack.razorpay.com` collects telemetry the SDK
          // treats as required. Allowing only the first blocked the iframe with
          // "This content is blocked. Contact the site owner to fix the issue."
          // and left the buyer unable to pay — a total checkout failure caused
          // by our own header, with no server error to point at it.
          "script-src 'self' 'unsafe-inline' 'unsafe-eval' https://checkout.razorpay.com https://cdn.razorpay.com https://www.googletagmanager.com https://www.google-analytics.com https://salesiq.zohopublic.in https://*.zohopublic.in https://*.zohocdn.com; " +
          "style-src 'self' 'unsafe-inline' https://fonts.googleapis.com https://*.zohopublic.in https://*.zohocdn.com; " +
          "font-src 'self' data: https://fonts.gstatic.com https://cdn.razorpay.com https://*.zohopublic.in https://*.zohocdn.com; " +
          "img-src 'self' data: https://*.razorpay.com https:; " +
          "connect-src 'self' https://api.razorpay.com https://lumberjack.razorpay.com https://checkout.razorpay.com https://cdn.razorpay.com https://apiv2.shiprocket.in https://www.google-analytics.com https://www.googletagmanager.com https://salesiq.zohopublic.in https://*.zohopublic.in https://*.zohocdn.com wss://*.zohopublic.in; " +
          "frame-src https://checkout.razorpay.com https://api.razorpay.com https://*.zohopublic.in; " +
          "worker-src 'self' blob:; " +
          "object-src 'none'; " +
          "base-uri 'self';",
      },
    ];

    if (process.env.NODE_ENV === "production") {
      headers.push({
        key: "Strict-Transport-Security",
        value: "max-age=63072000; includeSubDomains; preload",
      });
    }

    return [{ source: "/(.*)", headers }];
  },
};

module.exports = withNextIntl(nextConfig);
