/**
 * All six fields or nothing.
 *
 * A row with a Hindi title and an English essay underneath is the state this
 * file exists to end, so a partial record is treated as no Hindi at all.
 */
export function hindiFor(slug: string): ArtFormHindi | null {
  const entry = ART_FORM_HINDI[slug];
  if (!entry) return null;
  const complete = (
    ["name", "description", "story", "origin", "materials", "quote"] as const
  ).every((field) => (entry[field] || "").trim().length > 0);
  return complete ? entry : null;
}
