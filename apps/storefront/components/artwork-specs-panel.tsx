/**
 * The factual specification block on a product page.
 *
 * Art buyers decide with logistics as much as emotion: size, medium, framing,
 * whether it ships framed, how long it takes. Those facts used to live only in
 * the operator's head. Here they are out in the open — not inside a tab, not
 * inside a long description — because "how big is it and what is it made of" is
 * the second question after "what does it look like".
 *
 * Presentation is deliberately quiet: no card, no border per row, no shadow. A
 * two-column definition grid on the page ground, separated by a hairline, reads
 * as a museum wall label rather than a product listing.
 *
 * Only rows with a real value render. Nothing is invented to fill the grid.
 *
 * The row labels are translated. They used to be hard-coded English, which meant
 * the most factual block on a product page — the one a buyer uses to decide —
 * stayed in English on /hi while the heading above it read "विवरण".
 */
import { getTranslations } from "next-intl/server";
import type { ArtworkSpecs } from "@/lib/catalogue";

const ROWS: { key: keyof ArtworkSpecs }[] = [
  { key: "dimensions" },
  { key: "medium" },
  { key: "framing" },
  { key: "year" },
  { key: "edition" },
  { key: "dispatch" },
  { key: "care" },
  { key: "provenance" },
  { key: "condition" },
];

export async function ArtworkSpecsPanel({
  specs,
  title = "Details",
}: {
  specs: ArtworkSpecs;
  /** Heading text, so the surrounding copy can be translated. */
  title?: string;
}) {
  // Dimensions are the one row that renders even when empty. A work on sale with
  // no size at all does not get to look complete: the row says the measurement
  // is pending and points at the studio, rather than being quietly absent while
  // every other fact is present.
  const rows = ROWS.filter((row) => specs[row.key] || row.key === "dimensions");
  if (rows.length === 0) return null;

  const t = await getTranslations("productDetail.specs");

  // A dispatch line generated by the catalogue carries a message key; one
  // written by an editor as a tag is shown exactly as written.
  const valueFor = (row: (typeof ROWS)[number]) => {
    if (row.key === "dispatch" && specs.dispatchKey) return t(specs.dispatchKey);
    if (row.key === "dimensions" && !specs.dimensions) {
      return (
        <span className="italic text-muted-ink">{t("dimensionsToConfirm")}</span>
      );
    }
    return specs[row.key];
  };

  return (
    <section aria-labelledby="artwork-details">
      <h2
        id="artwork-details"
        className="font-sans text-[11px] font-semibold uppercase tracking-[0.22em] text-terracotta"
      >
        {title}
      </h2>

      <dl className="mt-4 divide-y divide-sand-border/50 border-y border-sand-border/60">
        {rows.map((row) => (
          <div
            key={row.key}
            className="grid grid-cols-[100px_1fr] items-baseline gap-4 py-2.5 sm:grid-cols-[150px_1fr]"
          >
            <dt className="font-sans text-[11px] uppercase tracking-[0.12em] text-muted-ink">
              {t(row.key)}
            </dt>
            <dd className="font-sans text-[13.5px] leading-relaxed text-deep-ink">
              {valueFor(row)}
              {/* A size nobody has measured is still worth showing — it is what
                  the studio says — but it is said as such, because the same
                  number is not what the certificate will carry until someone
                  confirms it. */}
              {row.key === "dimensions" && specs.dimensions && !specs.dimensionsMeasured && (
                <span className="text-muted-ink"> · {t("dimensionsStated")}</span>
              )}
            </dd>
          </div>
        ))}
      </dl>
    </section>
  );
}
